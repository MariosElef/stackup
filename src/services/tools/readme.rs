//! The generated project's README.
use crate::models::{Backend, Frontend, Plan, Service, Tool};

pub(super) fn generate(plan: &Plan) -> String {
    let mut s = format!("# {}\n\nGenerated by `stackup`.\n\n", plan.name);
    s.push_str(&format!(
        "- Frontend: {}\n- Backend: {}\n",
        plan.frontend, plan.backend
    ));
    let services: Vec<String> = plan.services.iter().map(ToString::to_string).collect();
    s.push_str(&format!(
        "- Services: {}\n\n",
        if services.is_empty() {
            "none".into()
        } else {
            services.join(", ")
        }
    ));

    if plan.tool(Tool::Makefile) {
        s.push_str("## Commands\n\nRun `make help` to list them. Each one is a short name for a longer command; the real commands are written in the `Makefile`.\n\n```\nmake up      # build and start everything in Docker\nmake dev     # databases in Docker, backend with reload\nmake ci      # the checks CI runs\nmake fmt     # format the code\n```\n\n");
    }
    s.push_str("## Run\n\n```sh\n");
    if plan.has(Service::Https) {
        s.push_str("./scripts/certs.sh      # once: a trusted local certificate (mkcert)\n");
    }
    s.push_str("docker compose up --build\n```\n\n");

    s.push_str("## Where things are\n\n");
    if plan.frontend != Frontend::None {
        s.push_str(&format!("- App: {}\n", plan.web_url()));
    }
    if plan.backend != Backend::None {
        s.push_str(&format!("- API: {}/health\n", plan.api_url()));
    }
    if plan.has(Service::Keycloak) {
        s.push_str(&format!(
            "- Keycloak: {} (admin / admin). Realm `app`, user `demo` / `demo`, clients `app-frontend` and `app-backend`.\n",
            plan.auth_url()
        ));
    }
    if plan.has(Service::Mailtrap) {
        s.push_str("- Mailtrap: set `MAILTRAP_USER` and `MAILTRAP_PASSWORD` from your inbox's SMTP settings.\n");
    }
    s.push_str("\n## Configuration\n\nSettings live in `.env` files, one per tier. `.env.example` is the committed template; `.env.local` is generated and copied to `.env`, which compose reads. Create `.env.dev` or `.env.prod` from the template and switch with `make env TIER=dev`. Everything except `.env.example` is gitignored.\n");
    s
}
